private fun signInWithGoogle(
    context: android.content.Context,
    credentialManager: CredentialManager,
    scope: CoroutineScope,
    onSuccess: (com.google.firebase.auth.FirebaseUser) -> Unit,
    onError: (String) -> Unit,
    onCancelled: () -> Unit
) {
    val clientId = try {
        val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        if (resId != 0) context.getString(resId) else ""
    } catch (e: Exception) {
        ""
    }
    if (clientId.isBlank()) {
        onError("Google Client ID bulunamadı. Lütfen google-services.json yapılandırmasını kontrol edin.")
        return
    }

    val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
    val request = GetCredentialRequest.Builder().addCredentialOption(signInOption).build()

    scope.launch {
        try {
            val result = credentialManager.getCredential(context as Activity, request)
            val credential = result.credential
            if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
                val authResult = Firebase.auth.signInWithCredential(authCredential).await()
                val user = authResult.user
                if (user != null) {
                    onSuccess(user)
                } else {
                    onError("Kullanıcı bilgisi alınamadı.")
                }
            } else {
                onError("Beklenmeyen kimlik türü.")
            }
        } catch (e: GetCredentialCancellationException) {
            Log.w("Auth", "Google Sign-In iptal edildi: ${e.message}")
            onCancelled()
        } catch (e: Exception) {
            Log.e("Auth", "Google Sign-In hatası", e)
            onError(e.localizedMessage ?: "Giriş başarısız oldu.")
        }
    }
}
